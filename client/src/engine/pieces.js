export const getCells = (type, rotation) =>
  PIECES[type].rotations[rotation];

export const getWallKicks = (type, fromRot, toRot) => {
  const key = `${fromRot}->${toRot}`;
  return type === 'I' ? (WALL_KICKS_I[key] || [[0,0]]) : (WALL_KICKS[key] || [[0,0]]);
};

